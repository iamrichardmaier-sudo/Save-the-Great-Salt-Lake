/**
 * Every coefficient the model uses, each with a basis stating where it came from.
 *
 * Rules this file keeps:
 *  - No number appears anywhere else in the code or in any sentence on screen. If a figure is
 *    shown to a reader, it is read from here or computed from here.
 *  - `status` is 'sourced' (a published figure), 'derived' (computed from other entries, with the
 *    formula given) or 'assumption' (no source: the basis says why, and the UI flags it).
 *  - `low`/`high` bound the sensitivity sweep and the dial range.
 */

import { source, type Source } from './sources';

export type Status = 'sourced' | 'derived' | 'assumption';
export type Confidence = 'High' | 'Medium' | 'Low';

export interface Coef {
  id: string;
  label: string;
  value: number;
  unit: string;
  group: string;
  status: Status;
  /** Where the number comes from, or why it is an assumption. */
  basis: string;
  sourceIds: string[];
  /** For derived values: how it is computed. */
  formula?: string;
  low?: number;
  high?: number;
  confidence?: Confidence;
  note?: string;
}

export type LegalStatus = 'Current law' | 'Model interpretation' | 'Proposed legislation';

