const BY_ID = new Map(C.map((c) => [c.id, c]));

/** The value of a coefficient. Throws on an unknown id, so a typo fails loudly. */
export function V(id: string): number {
  const c = BY_ID.get(id);
  if (!c) throw new Error(`Unknown coefficient: ${id}`);
  return c.value;
}

/**
 * Run `fn` with some coefficients temporarily changed. The sweep uses this so it can push an
 * assumption to the edge of its range without every call site having to thread values through.
 * Synchronous only: the values are restored before it returns.
 */
export function withCoefs<T>(overrides: Record<string, number>, fn: () => T): T {
  const saved: Record<string, number> = {};
  for (const [id, value] of Object.entries(overrides)) {
    const c = BY_ID.get(id);
    if (!c) throw new Error(`Unknown coefficient: ${id}`);
    saved[id] = c.value;
    c.value = value;
  }
  try {
    return fn();
  } finally {
    for (const [id, value] of Object.entries(saved)) {
      BY_ID.get(id)!.value = value;
    }
  }
}

export function coef(id: string): Coef {
  const c = BY_ID.get(id);
  if (!c) throw new Error(`Unknown coefficient: ${id}`);
  return c;
}

export function coefSources(id: string): Source[] {
  return coef(id).sourceIds.map(source);
}

export function allGroups(): string[] {
  return [...new Set(C.map((c) => c.group))];
}

